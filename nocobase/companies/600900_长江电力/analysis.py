# ================================================================ SQL
def _ins(table, rows):
    if not rows:
        return ''
    cols = list(rows[0].keys())
    vals = ',\n'.join('(' + ', '.join(r[c].sql if isinstance(r.get(c), Raw) else lit(r.get(c)) for c in cols) + ')' for r in rows)
    return f'INSERT INTO vi_{table}_base ({", ".join(cols)}) VALUES\n{vals};'


class Raw:
    def __init__(self, sql):
        self.sql = sql


def _src(title):
    return Raw(f"(SELECT id FROM vi_source_base WHERE company_id = {CO} AND title = {lit(title)} LIMIT 1)")


def _link(table, field, target, pairs, key, tkey):
    if not pairs:
        return ''
    a, b = f'{table}_id', f'{target}_id'
    return (f"INSERT INTO vi_lnk_{table}_{field} ({a}, {b}, \"createdAt\", \"updatedAt\")\n"
            f"SELECT x.id, y.id, now(), now() FROM (VALUES {', '.join(f'({lit(p)}, {lit(q)})' for p, q in pairs)}) v(k1, k2)\n"
            f"JOIN vi_{table}_base x ON x.company_id = {CO} AND x.{key} = v.k1 JOIN vi_{target}_base y ON y.company_id = {CO} AND y.{tkey} = v.k2;")


