def link(table, field, target, pairs, key, tkey):
    """多对多关联：按业务键（编号、标题、名称）连接本公司的两张表。"""
    if not pairs:
        return
    a, b = f'{table}_id', f'{target}_id'
    OUT.append(f"""INSERT INTO vi_lnk_{table}_{field} ({a}, {b}, "createdAt", "updatedAt")
SELECT x.id, y.id, now(), now() FROM (VALUES {', '.join(f'({lit(p)}, {lit(q)})' for p, q in pairs)}) v(k1, k2)
JOIN vi_{table}_base x ON x.company_id = {CO} AND x.{key} = v.k1 JOIN vi_{target}_base y ON y.company_id = {CO} AND y.{tkey} = v.k2;""")


